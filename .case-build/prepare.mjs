// Prepares the case study renderer that runs inside this site's case window, from the portfolio (read-only).
// - copies the portfolio's renderer verbatim,
// - generates the data module from the portfolio's src/projects.js (text untouched),
// - copies every referenced media file byte for byte into the site's cases/<project>/,
// - scopes the portfolio's styles under .zz-case so they never reach the rest of the site.
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const PORT = '/Users/ziruizhao/Documents/PersonalPortfolioWebsite';
const HERE = path.dirname(new URL(import.meta.url).pathname);
const SITE = path.dirname(HERE);
const KEYS = ['zeen', 'allot'];

// ---- data: the JSON object inside `export const projects = { … };` --------------------------
const source = fs.readFileSync(`${PORT}/src/projects.js`, 'utf8');
const start = source.indexOf('{', source.indexOf('export const projects ='));
const all = JSON.parse(source.slice(start, source.indexOf('\n};', start) + 2));
const projects = Object.fromEntries(KEYS.map(k => [k, all[k]]));
// The Zeen prototype is its own app at zirui.ca/zeen/ and isn't copied here, so its link points there.
for (const section of projects.zeen.sections) for (const part of section.content ?? []) {
  if (part.type === 'prototype' && part.href === '/zeen/') part.href = 'https://zirui.ca/zeen/';
}
// Copy edits asked for on this site that the portfolio doesn't have (yet).
const EDITS = { 'Change the background while reading': 'Change the background while reading.' };
const edit = node => {
  if (Array.isArray(node)) return node.forEach(edit);
  if (node && typeof node === 'object') for (const [k, v] of Object.entries(node)) {
    if (typeof v === 'string' && Object.hasOwn(EDITS, v)) node[k] = EDITS[v]; else edit(v);
  }
};
edit(projects);

// ---- media each project needs -----------------------------------------------------------------
function referenced(project) {
  const files = new Set();
  const visit = (node, key) => {
    if (Array.isArray(node)) return node.forEach(item => visit(item, key));
    if (node && typeof node === 'object') return Object.entries(node).forEach(([k, v]) => visit(v, k));
    if (typeof node === 'string' && ['file', 'image', 'files', 'cover', 'walkthrough', 'video', 'poster', 'images'].includes(key)) files.add(node);
  };
  visit(project);
  return files;
}
const scenes = JSON.parse(fs.readFileSync(`${PORT}/src/illustration-layers.json`, 'utf8'));
const report = {};
for (const key of KEYS) {
  const project = projects[key];
  const direct = referenced(project);
  // Every clip in the sections has a poster beside it (the hero walkthrough uses the cover instead).
  const posters = new Set();
  const clipVisit = node => {
    if (Array.isArray(node)) return node.forEach(clipVisit);
    if (node && typeof node === 'object') {
      if (typeof node.file === 'string' && node.file.endsWith('.mp4')) posters.add(node.file.replace('.mp4', '-poster.webp'));
      Object.values(node).forEach(clipVisit);
    }
  };
  clipVisit(project.sections);
  const layers = new Set();
  for (const image of project.images ?? []) if (image.scene) scenes[image.scene].layers.forEach(layer => layers.add(layer.file));
  // The prototype frame's hover gradient comes from the stylesheet.
  const styled = key === 'zeen' ? ['zeen-prototype-gradient.webp'] : [];
  const files = [...new Set([...direct, ...posters, ...layers, ...styled])];
  fs.mkdirSync(`${SITE}/cases/${key}`, { recursive: true });
  const missing = [];
  for (const file of files) {
    const from = `${PORT}/assets/projects/${file}`;
    if (fs.existsSync(from)) fs.copyFileSync(from, `${SITE}/cases/${key}/${file}`); else missing.push(file);
  }
  report[key] = { referencedInProjectsJs: direct.size, clipPosters: posters.size, illustrationLayers: layers.size, copied: files.length - missing.length, missing };
}
fs.mkdirSync(`${SITE}/cases/prism`, { recursive: true });
for (const file of [all.prism.card.video, all.prism.card.poster]) fs.copyFileSync(`${PORT}/assets/projects/${file}`, `${SITE}/cases/prism/${file}`);
report.prism = { copied: 2 };

// ---- renderer, verbatim ----------------------------------------------------------------------
for (const file of ['case-study.js', 'illustrations.js', 'icons.js', 'work-layout.js', 'illustration-layers.json']) {
  fs.copyFileSync(`${PORT}/src/${file}`, `${HERE}/src/${file}`);
}

// ---- generated data module: same data, media served from cases/<project>/ ------------------
fs.writeFileSync(`${HERE}/src/projects.js`, `// Generated by prepare.mjs from the portfolio's src/projects.js. Do not edit by hand.
export const projects = ${JSON.stringify(projects, null, 2)};
// The window shows one project at a time; its media sits in the site's cases/<project>/ folder.
let media = '';
export const setProjectMedia = key => { media = new URL(\`cases/\${key}/\`, document.baseURI).href; };
export const projectImage = file => media + file;
export const projectVideo = file => media + file;
`);

// ---- styles: the portfolio's layout rules (no Marr typefaces) plus this site's theme, all under .zz-case
const SCOPE = '.zz-case';
const rootish = /^(?::root|html|body)((?:\[[^\]]*\]|:[\w-]+(?:\((?:[^()]|\([^()]*\))*\))?|\.[\w-]+)*)\s*(.*)$/;
// A page-level qualifier holds only if it describes a case study page.
const holds = qualifiers => !qualifiers || /^(?:\[data-page=project\]|:has\(body\[data-page=project\]\))$/.test(qualifiers);
const scope = () => ({
  postcssPlugin: 'scope',
  Rule(rule) {
    if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    if (rule.selector.startsWith(SCOPE) || rule.raws.scoped) return;
    const selectors = rule.selectors.flatMap(selector => {
      const s = selector.trim();
      const m = s.match(rootish);
      if (m) return holds(m[1]) ? [m[2] ? `${SCOPE} ${m[2]}` : SCOPE] : [];
      return [`${SCOPE} ${s}`];
    });
    if (!selectors.length) { rule.remove(); return; }
    rule.selectors = selectors;
    rule.raws.scoped = true;
  },
});
const portfolioCss = fs.readFileSync(`${PORT}/src/style.css`, 'utf8')
  .replace(/@font-face\{[^}]*\}/g, '')
  .replace("url('../assets/projects/zeen-prototype-gradient.webp')", "url('cases/zeen/zeen-prototype-gradient.webp')");
const theme = fs.readFileSync(`${HERE}/src/case-theme.css`, 'utf8');
const scoped = postcss([scope()]).process(portfolioCss + '\n' + theme, { from: undefined }).css;
const outside = fs.readFileSync(`${HERE}/src/case-window.css`, 'utf8');
fs.writeFileSync(`${HERE}/src/embed-css.js`, `// Generated by prepare.mjs. Do not edit by hand.\nexport default ${JSON.stringify(scoped + '\n' + outside)};\n`);
console.log(JSON.stringify(report, null, 2));
